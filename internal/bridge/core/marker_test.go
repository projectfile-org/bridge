// spdxLicenseLine builds the REUSE licence-declaration line WITHOUT spelling
// the SPDX tag as a source literal — the REUSE linter scans source for that
// token and would flag a test fixture as a malformed licence expression.
const spdxTag = "SPDX-License-"

func spdxLicenseLine(expr string) string { return spdxTag + "Identifier: " + expr }

// TestHasMarkerRecognizesAllForms pins detection of the three sentinel shapes
// a generated file may carry: the hash-leader line (ignore files), the
// HTML-comment line (Markdown health files), and the bare inner text folded
// into a merged SPDX block (the README).
func TestHasMarkerRecognizesAllForms(t *testing.T) {
	t.Parallel()

	mergedHeader := "<!--\n" + spdxLicenseLine("MIT") + "\n" + MarkerInner + "\n-->\n"

	cases := []struct {
		input string
		want  bool
	}{
		{Marker + "\nbody\n", true},
		{MarkerHTML + "\nbody\n", true},
		{MarkerInner + "\nbody\n", true},
		{MarkerSlash + "\nbody\n", true},
		{mergedHeader, true},
		{"no marker here at all\n", false},
		{"", false},
	}
	for _, tc := range cases {
		assert.Equal(t, tc.want, HasMarker([]byte(tc.input)), "input=%q", tc.input)
	}
}

// Banner is the whole block an ignore-file renderer emits: filename, namespace pointer, sentinel.
func TestBannerCarriesFilenameNamespaceAndMarker(t *testing.T) {
	got := Banner(".gitignore", "git")

	assert.Contains(t, got, "# .gitignore — generated by")
	assert.Contains(t, got, "[org.projectfile.ignores.git]")
	assert.Contains(t, got, Marker)
	assert.True(t, strings.HasSuffix(got, "\n\n"), "one blank line separates the banner from content")
	assert.NotContains(t, got, "# Editors:", "no editors were declared")
}

// BannerWithEditors inserts the Editors line only when editors exist.
func TestBannerWithEditorsAddsTheLineOnlyWhenDeclared(t *testing.T) {
	got := BannerWithEditors(".gitignore", "git", []string{"vim", "vscode"})
	assert.Contains(t, got, "# Editors: vim, vscode\n")
	assert.Contains(t, got, Marker)

	assert.Equal(t, Banner(".gitignore", "git"), BannerWithEditors(".gitignore", "git", nil))
}
